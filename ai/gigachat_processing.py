import os

from dotenv import load_dotenv
from gigachat import GigaChat

load_dotenv()
api_key = os.getenv("GIGACHAT_API_KEY")
if not api_key:
    raise ValueError("GIGACHAT_API_KEY is empty")

client = GigaChat(
    credentials=api_key,
    scope="GIGACHAT_API_PERS",
    model="GigaChat-2",
    verify_ssl_certs=False,
)


def get_categorized_description(joined_cards: str) -> str | None:
    """
    This function get card description from the Parser in parse_kwork.py and process it by prompt
    Then, function returns output from the AI
    """
    ru_prompt = f"""Ты — опытный менеджер проектов и аналитик фриланс-заказов. Твоя задача — проанализировать карточки заказов, извлечь из них ключевые требования и очистить от "воды".

    СТРОГИЕ ПРАВИЛА (НАРУШАТЬ НЕЛЬЗЯ):
    1. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО писать любые вступления, комментарии от себя, выводы или описания качества текста (ЗАПРЕЩЕНО писать фразы вроде "Анализ показал...", "Текст лаконичный...", "Нет информации для анализа"). Ответ должен сразу начинаться с первой заголовка.
    2. Если конкретные инструменты или навыки не указаны явно, но они ЛОГИЧЕСКИ ОЧЕВИДНЫ из задачи (например, для заказа "сделать логотип" очевидны "Графический дизайн" и "Photoshop/Illustrator") — ОБЯЗАТЕЛЬНО укажи их.
    3. Если навык или инструмент определить невозможно совсем — пиши строго: "- Не указано".
    4. Если в заказе вообще нет деталей (например, "срочно напиши в лс"), в сути задачи напиши: "Мало информации. Исходный текст: [пересказ в 1 предложение]".
    5. Если в тексте передано несколько карточек, выводи указанный ниже блок форматирования ДЛЯ КАЖДОЙ карточки по очереди, разделяя их чертой "---".

    Формат вывода строго следующий:

    ### 📋 Карточка [Номер или Название]

    **🎯 Необходимые навыки:**
    - [Навык 1]
    - [Навык 2]

    **🛠 Инструменты и технологии:**
    - [Инструмент 1]
    - [Инструмент 2]

    **📝 Суть задачи (выжимка):**
    [Краткое описание задачи в 2-4 предложениях, только суть]

    Вот текст заказов для анализа:
    {joined_cards}
    """
    try:
        response = client.chat(ru_prompt)
        content = response.choices[0].message.content
    except Exception as e:
        print(e)
        return

    return content



