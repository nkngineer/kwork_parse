import os

from dotenv import load_dotenv
from mistralai.client import Mistral

load_dotenv()
api_key = os.getenv("MISTRAL_API_KEY")
if not api_key:
    raise ValueError("Mistral API key is empty")

client = Mistral(api_key)


def get_categorized_description(joined_cards: str) -> str | None:
    """
    This function get card description from the Parser in parse_kwork.py and process it by prompt
    Then, function returns output from the AI
    """

    ru_prompt = f"""
    Ты — опытный системный аналитик и HR-специалист. Твоя задача — проанализировать сырое описание требований к заданию (или вакансии), извлечь из него ключевую информацию и очистить от "воды".

    Твои шаги:
    1. Проанализируй текст и выдели все необходимые навыки (hard skills и soft skills), которые требуются для выполнения задачи.
    2. Выдели все конкретные инструменты, технологии, программы, языки программирования или платформы, которые упоминаются или логически необходимы для работы.
    3. Составь краткое, четкое и емкое описание самой задачи, удалив все лишние вводные слова, корпоративный жаргон и нерелевантные детали. Оставь только суть: что конкретно нужно сделать и каков ожидаемый результат.

    Формат вывода строго следующий:

    **🎯 Необходимые навыки:**
    - [Навык 1]
    - [Навык 2]

    **🛠 Инструменты и технологии:**
    - [Инструмент 1]
    - [Инструмент 2]

    **📝 Суть задачи (выжимка):**
    [Краткое описание задачи в 2-4 предложениях, только самое важное]

    Вот текст для анализа:
    {joined_cards}
    """

    try:
        response = client.chat.complete(
            model="mistral-large-latest",
            messages=[
                {
                    "role": "user",
                    "content": ru_prompt,
                }
            ],
        )
        content = response.choices[0].message.content

    except Exception as e:
        print(f"Response error: {e}")
        return None

    return content


